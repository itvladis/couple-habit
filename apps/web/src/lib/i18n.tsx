export type Lang = 'ru' | 'en';

type Forms = { one: string; few?: string; many?: string; other: string };

export function plural(lang: Lang, n: number, forms: Forms): string {
  const rule = new Intl.PluralRules(lang).select(n);
  const word = (rule === 'one' && forms.one) || (rule === 'few' && forms.few) || (rule === 'many' && forms.many) || forms.other;
  return `${n} ${word}`;
}

